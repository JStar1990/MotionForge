import { expect, test } from '@playwright/test';
test('3D 模型、双机隔离、解锁与撤销', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('status')).toContainText('模型已加载');
  const capture = page.getByTestId('capture-view').locator('canvas');
  const before = await capture.screenshot();
  await page.getByRole('button', { name: '左侧', exact: true }).click();
  await expect(async () => expect(await capture.screenshot()).toEqual(before)).toPass();
  await page.getByRole('button', { name: '解锁截图摄像机' }).click();
  await page.getByRole('button', { name: '采用当前自由视角' }).click();
  await expect(page.getByLabel('截图投影')).toHaveValue('perspective');
  await page.getByRole('button', { name: '撤销相机调整' }).click();
  await expect(page.getByLabel('截图投影')).toHaveValue('orthographic');
  await page.getByRole('button', { name: '锁定截图摄像机' }).click();
  await expect(page.getByLabel('position-0')).toBeDisabled();
  await page.screenshot({ path: info.outputPath('scene3d.png'), fullPage: true });
  await page.getByLabel('素体模型').selectOption('female');
  await expect(page.getByRole('status')).toContainText('模型已加载');
  await page.getByRole('button', { name: '打开原 2D 编辑器' }).click();
  await expect(page.getByTestId('pose-canvas')).toBeVisible();
  expect(errors).toEqual([]);
});

test('3D FK 编辑、撤销重做、相机比例与裁剪验证', async ({ page }, info) => {
  await page.goto('/');
  await expect(page.getByRole('status')).toContainText('模型已加载');
  const capture = page.getByTestId('capture-view').locator('canvas');
  const before = await capture.screenshot();
  const rotation = page.getByLabel('骨骼旋转 X', { exact: true });
  await rotation.fill('70');
  await rotation.press('Enter');
  await expect(rotation).toHaveValue('70');
  await expect(async () => expect(await capture.screenshot()).not.toEqual(before)).toPass();
  await page.getByRole('button', { name: '撤销姿势', exact: true }).click();
  await expect(rotation).toHaveValue('0');
  await expect(async () => expect(await capture.screenshot()).toEqual(before)).toPass();
  await page.getByRole('button', { name: '重做姿势', exact: true }).click();
  await expect(rotation).toHaveValue('70');
  await page.getByLabel('选择 3D 骨骼').selectOption('upperarm_r');
  await rotation.fill('-70');
  await rotation.press('Enter');
  await page.getByRole('button', { name: '解锁截图摄像机' }).click();
  await page.getByLabel('截图比例').selectOption(String(16 / 9));
  await expect(capture).toHaveAttribute('height', '288');
  await page.getByLabel('截图投影').selectOption('perspective');
  await page.getByLabel('透视视野').fill('60');
  await expect(page.getByLabel('透视视野')).toHaveValue('60');
  await page.getByLabel('近裁剪面').fill('200');
  await expect(page.getByLabel('近裁剪面')).toHaveValue('0.01');
  await page.screenshot({ path: info.outputPath('fk-camera.png'), fullPage: true });
  await page.getByRole('button', { name: '重置 3D 姿势' }).click();
  await expect(rotation).toHaveValue('0');
});

test('视图骨骼旋转、一次撤销、Esc 取消与辅助层隔离', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('status')).toContainText('模型已加载');
  await page.getByRole('button', { name: '左侧', exact: true }).click();
  const capture = page.getByTestId('capture-view').locator('canvas');
  const before = await capture.screenshot();
  await page.getByLabel('显示骨骼控制点').uncheck();
  await expect(async () => expect(await capture.screenshot()).toEqual(before)).toPass();
  await page.getByLabel('显示骨骼控制点').check();
  await page.mouse.click(558, 792);
  await expect(page.getByLabel('选择 3D 骨骼')).not.toHaveValue('upperarm_l');
  await page.getByLabel('选择 3D 骨骼').selectOption('upperarm_l');
  // Stable side view at the configured 1440×960 viewport: green local rotation ring.
  await page.mouse.move(610, 452);
  await page.mouse.down();
  await page.mouse.move(580, 475, { steps: 12 });
  await page.mouse.up();
  await expect(page.getByRole('button', { name: '撤销姿势', exact: true })).toBeEnabled();
  await expect(async () => expect(await capture.screenshot()).not.toEqual(before)).toPass();
  await page.getByRole('button', { name: '撤销姿势', exact: true }).click();
  await expect(async () => expect(await capture.screenshot()).toEqual(before)).toPass();
  await expect(page.getByRole('button', { name: '撤销姿势', exact: true })).toBeDisabled();
  await page.mouse.move(610, 452);
  await page.mouse.down();
  await page.mouse.move(580, 475, { steps: 12 });
  await page.keyboard.press('Escape');
  await page.mouse.up();
  await expect(async () => expect(await capture.screenshot()).toEqual(before)).toPass();
  await expect(page.getByRole('button', { name: '撤销姿势', exact: true })).toBeDisabled();
});

test('骨架辅助、世界轴切换和关节聚焦不改变截图或姿势', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('status')).toContainText('模型已加载');
  const capture = page.getByTestId('capture-view').locator('canvas');
  const free = page.getByTestId('free-view').locator('canvas');
  const outputBefore = await capture.screenshot();
  await page.getByLabel('旋转轴空间').selectOption('world');
  await expect(page.getByLabel('旋转轴空间')).toHaveValue('world');
  await page.getByLabel('选择 3D 骨骼').selectOption('foot_l');
  const freeBefore = await free.screenshot();
  await page.getByRole('button', { name: '聚焦选中骨骼' }).click();
  await expect(async () => expect(await free.screenshot()).not.toEqual(freeBefore)).toPass();
  await expect(async () => expect(await capture.screenshot()).toEqual(outputBefore)).toPass();
  await page.getByLabel('显示骨骼控制点').uncheck();
  await expect(async () => expect(await capture.screenshot()).toEqual(outputBefore)).toPass();
  await expect(page.getByRole('button', { name: '撤销姿势', exact: true })).toBeDisabled();
  await page.getByLabel('旋转轴空间').selectOption('local');
  await page.getByLabel('显示骨骼控制点').check();
  await page.getByLabel('素体模型').selectOption('female');
  await expect(page.getByRole('status')).toContainText('模型已加载');
  await expect(page.getByLabel('旋转轴空间')).toHaveValue('local');
});

